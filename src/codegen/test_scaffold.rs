//! `blast gen test` — emit baseline integration test scaffolds wired to the
//! catalyst testing harness (`with_test_transaction`, `TestCtx`, `Fixture`,
//! `fixture!`). Idempotent: existing files are left untouched.

use std::fs;
use std::path::{Path, PathBuf};

use crate::codegen::ir_loader;
use crate::error::BlastResult;
use crate::state::{ResourceState, Verb};

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Filter {
    All,
    Flow(String),
    Route(String),
}

#[derive(Debug, Default)]
pub struct EmitReport {
    pub written: Vec<PathBuf>,
    pub skipped: Vec<PathBuf>,
}

pub fn run(project_root: &Path, filter: &Filter) -> BlastResult<EmitReport> {
    let resources = ir_loader::load_resource_states(project_root)?;
    let mut report = EmitReport::default();

    write_once(
        &project_root.join("tests").join("common").join("mod.rs"),
        &common_mod_rs(),
        &mut report,
    )?;

    for r in &resources {
        if !filter.includes_resource(r) {
            continue;
        }

        write_once(
            &fixture_path(project_root, r.name.as_str()),
            &fixture_stub(r.name.as_str()),
            &mut report,
        )?;

        if filter.includes_routes(r) {
            write_once(
                &route_test_path(project_root, r.name.as_str()),
                &route_test_stub(r.name.as_str()),
                &mut report,
            )?;
        }

        for verb in r.verbs.keys() {
            if !filter.includes_verb(r.name.as_str(), *verb) {
                continue;
            }
            write_once(
                &flow_test_path(project_root, r.name.as_str(), *verb),
                &flow_test_stub(r.name.as_str(), *verb),
                &mut report,
            )?;
        }
    }

    write_once(
        &project_root.join("tests").join("fixtures").join("mod.rs"),
        &fixtures_mod_rs(&resources),
        &mut report,
    )?;

    Ok(report)
}

impl Filter {
    fn includes_resource(&self, r: &ResourceState) -> bool {
        match self {
            Filter::All => true,
            Filter::Flow(name) => {
                name == r.name.as_str()
                    || name.starts_with(&format!("{}/", r.name.as_str()))
            }
            Filter::Route(name) => name == r.name.as_str(),
        }
    }

    fn includes_routes(&self, r: &ResourceState) -> bool {
        match self {
            Filter::All => true,
            Filter::Route(name) => name == r.name.as_str(),
            Filter::Flow(_) => false,
        }
    }

    fn includes_verb(&self, table: &str, verb: Verb) -> bool {
        match self {
            Filter::All => true,
            Filter::Route(_) => false,
            Filter::Flow(name) => {
                let want = format!("{}/{}", table, verb_module(verb));
                name == &want || name == table
            }
        }
    }
}

fn write_once(target: &Path, body: &str, report: &mut EmitReport) -> BlastResult<()> {
    if target.exists() {
        report.skipped.push(target.to_path_buf());
        return Ok(());
    }
    let parent = target.parent().ok_or_else(|| {
        crate::error::BlastError::Invalid(format!(
            "scaffold target has no parent: {}",
            target.display()
        ))
    })?;
    fs::create_dir_all(parent)?;
    fs::write(target, body)?;
    report.written.push(target.to_path_buf());
    Ok(())
}

fn fixture_path(project_root: &Path, table: &str) -> PathBuf {
    project_root
        .join("tests")
        .join("fixtures")
        .join(format!("{}.rs", table))
}

fn route_test_path(project_root: &Path, table: &str) -> PathBuf {
    project_root
        .join("src")
        .join("transport")
        .join("http")
        .join("generated")
        .join(format!("{}.test.rs", table))
}

fn flow_test_path(project_root: &Path, table: &str, verb: Verb) -> PathBuf {
    project_root
        .join("src")
        .join("flows")
        .join("generated")
        .join(table)
        .join(format!("{}.test.rs", verb_module(verb)))
}

fn verb_module(verb: Verb) -> &'static str {
    match verb {
        Verb::List => "list",
        Verb::Get => "get",
        Verb::Create => "create",
        Verb::Update => "update",
        Verb::Delete => "delete",
    }
}

fn common_mod_rs() -> String {
    String::from(COMMON_MOD_RS)
}

