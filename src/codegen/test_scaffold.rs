fn flow_test_stub(table: &str, verb: Verb) -> String {
    let verb_str = verb_module(verb);
    let singular = singularize(table);
    let type_name = pascal_case(&singular);

    let body = match verb {
        Verb::Create => CREATE_BODY.to_string(),
        Verb::List => LIST_BODY.replace("__TYPE__", &type_name),
        Verb::Get => GET_BODY.replace("__TYPE__", &type_name),
        Verb::Update => UPDATE_BODY.replace("__TYPE__", &type_name),
        Verb::Delete => DELETE_BODY.replace("__TYPE__", &type_name),
    };

    FLOW_TEMPLATE
        .replace("__TABLE__", table)
        .replace("__VERB__", verb_str)
        .replace("__TYPE__", &type_name)
        .replace("__BODY__", &body)
}

